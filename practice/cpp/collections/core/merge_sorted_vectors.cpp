#include <algorithm>
#include <iterator>
#include <vector>

std::vector<int> solve(const std::vector<int>& left,
                       const std::vector<int>& right) {
    std::vector<int> result;
    result.reserve(left.size() + right.size());
    // Finish: combine both ascending inputs into one ascending result, retaining duplicates
    return result;
}
